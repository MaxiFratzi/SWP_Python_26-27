# if-Verzweigungen:
#   Verzweigungen sind in Python ziemlich ähnlich zu anderen Programmiersprachen. Ein wesentlicher Unterschied
#   ist unter anderem, dass z.B. das else if aus Java einfach zu elif werden. 
#   Außerdem ist es in Python grundsätzlich so, dass man für Funktionen, Verzweigungen, etc. keine geschwungenen Klammern
#   braucht. In Pyhton wird das Ganze mit Hilfe von Einrückungen geregelt. Statt der { schreibt man nur einen Doppelpunkt 
#   und rückt dann den Code ein, der innerhalb der Funktion, etc. stehen soll. Um dann wieder aus der Funktion, etc. 
#   zu kommen geht man einfach eine Einrückung zurück. Außerdem werden in Python keine ; wie in Java oder anderen
#   Programmiersprachen benötigt.

alter = 18
if alter >= 18:
    print("Erwachsen")
else:
    print("Nicht Erwachsen")